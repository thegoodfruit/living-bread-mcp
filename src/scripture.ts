const ALIAS: Record<string, string> = {};
for (const b of BOOKS) {
  ALIAS[squash(b.name)] = b.id;
  ALIAS[b.id] = b.id;
  for (const a of b.aliases) ALIAS[a] = b.id;
}
ALIAS.psalms = 'psalms';

function squash(s: string): string {
  return s.toLowerCase().replace(/[\s.]+/g, '');
}

export interface ParsedReference {
  bookId: string;
  book: string;
  chapter: number;
  /** First verse. Absent means the whole chapter. */
  from?: number;
  /** Last verse, inclusive. Absent means a single verse (or the whole chapter). */
  to?: number;
  /** The reference as a reader would say it: "John 3:16", "Psalm 23", "Romans 8:38-39". */
  ref: string;
}

export function bookById(id: string): BookMeta | undefined {
  return BOOKS.find((b) => b.id === id);
}

/** "1 John", "I John", "First John", "1st John", "1John" all mean the same book. */
function normalizeBook(raw: string): string {
  let s = raw.trim().toLowerCase().replace(/\./g, ' ').replace(/\s+/g, ' ');
  s = s
    .replace(/^(first|1st)\s+/, '1 ')
    .replace(/^(second|2nd)\s+/, '2 ')
    .replace(/^(third|3rd)\s+/, '3 ')
    .replace(/^iii\s+/, '3 ')
    .replace(/^ii\s+/, '2 ')
    .replace(/^i\s+/, '1 ');
  return squash(s);
}

/**
 * Parse a human reference. Accepts "John 3:16", "john 3.16", "Jn 3:16-18",
 * "1 Cor 13", "Psalm 23", "Song of Songs 2:1", "Romans 8:38-39" (also with a long dash).
 * Returns null for anything it cannot read with certainty, and clamps
 * nothing: a chapter past the book is null, not chapter 1.
 */
export function parseReference(input: string): ParsedReference | null {
  if (typeof input !== 'string') return null;
  const s = input
    .replace(/[\u2013\u2014]/g, '-')
    .replace(/\s*:\s*/g, ':')
    .replace(/\s*-\s*/g, '-')
    .trim();
  const m = s.match(/^(.*?[a-zA-Z])\.?\s*(\d{1,3})(?:[:.](\d{1,3})(?:-(\d{1,3}))?)?$/);
  if (!m) return null;
  const bookId = ALIAS[normalizeBook(m[1])];
  const book = bookId ? bookById(bookId) : undefined;
  if (!book) return null;
  const chapter = parseInt(m[2], 10);
  if (!(chapter >= 1 && chapter <= book.chapters)) return null;
  const from = m[3] ? parseInt(m[3], 10) : undefined;
  let to = m[4] ? parseInt(m[4], 10) : undefined;
  if (from !== undefined && from < 1) return null;
  if (to !== undefined && from !== undefined && to <= from) to = undefined;
  const parsed: ParsedReference = { bookId, book: book.name, chapter, ref: '' };
  if (from !== undefined) parsed.from = from;
  if (to !== undefined) parsed.to = to;
  parsed.ref = canonicalReference(parsed);
  return parsed;
}

export function canonicalReference(p: Omit<ParsedReference, 'ref'>): string {
  const base = `${p.book} ${p.chapter}`;
  if (p.from === undefined) return base;
  return p.to === undefined ? `${base}:${p.from}` : `${base}:${p.from}-${p.to}`;
}

/** The key the WEB cache is stored under: "john.3.16-16". */
export function refKey(p: Omit<ParsedReference, 'ref'>): string | null {
  if (p.from === undefined) return null;
  return `${p.bookId}.${p.chapter}.${p.from}-${p.to ?? p.from}`;
}

export interface Verse {
  verse: number;
  text: string;
}

/**
 * The verses of a span from one chapter of a stored book. A span that runs
 * past the chapter is cut at the chapter's end, never padded; a span with
 * nothing in it is an empty list. Nothing is added to the words.
 */
export function selectVerses(chapter: readonly string[] | undefined | null, from?: number, to?: number): Verse[] {
  if (!chapter || !chapter.length) return [];
  const start = from ?? 1;
  const end = from === undefined ? chapter.length : Math.max(start, to ?? start);
  const out: Verse[] = [];
  for (let v = start; v <= end; v++) {
    const t = chapter[v - 1];
    if (typeof t !== 'string') break;
    const clean = t.trim();
    if (clean) out.push({ verse: v, text: clean });
  }
  return out;
}

/** One line from several verses, as the app's own verseLine does. */
export function joinVerses(verses: readonly Verse[]): string {
  return verses.map((v) => v.text).join(' ').replace(/[,;:]\s*$/, '');
}

export type Translation = 'KJV' | 'WEB';

const WEB_CACHE = WEB as Record<string, { ref: string; text: string }>;

/** The World English Bible words for a span, only when the repo's cache holds exactly that span. */
export function webPassage(p: Omit<ParsedReference, 'ref'>): { ref: string; text: string } | null {
  const k = refKey(p);
  if (!k) return null;
  const hit = WEB_CACHE[k];
  if (hit) noteReading({ ref: hit.ref, translation: 'WEB', text: hit.text });
  return hit ? { ref: hit.ref, text: hit.text } : null;
}

export function webPassageCount(): number {
  return Object.keys(WEB_CACHE).length;
}

/** A URL slug for a verse, the way the web pages name them: john-3-16. */
export function verseSlug(p: Omit<ParsedReference, 'ref'>): string {
  const book = p.book.toLowerCase().replace(/\s+/g, '-');
  if (p.from === undefined) return `${book}-${p.chapter}`;
  return `${book}-${p.chapter}-${p.from}`;
}
