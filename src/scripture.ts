/* ============================================================
   THE LIVING BREAD MCP, Scripture: references, never typed words.

   The rule of this house is that no verse is ever typed from memory. A tool
   holds a REFERENCE; the words come from the King James Version the app
   itself ships (assets/bible/books, read through the ASSETS binding) or from
   the World English Bible cache the repo already holds (src/data/web.json,
   generated by scripts/build-data.py). A reference that cannot be resolved
   returns null, which is honest, never a half remembered line.

   This file is pure: no bindings, no fetch, so it can be tested anywhere.
   ============================================================ */
