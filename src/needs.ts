function words(s: string): string[] {
  return s.toLowerCase().replace(/[^a-z\s'-]/g, ' ').split(/\s+/).filter(Boolean);
}

export interface NeedMatch {
  need: Need;
  /** What in the question matched: a slug, a label, or a word people say. */
  matched: string;
}

/**
 * Find the need a person is naming. Exact slug or label first, then a
 * synonym of what they said, then a slug or label that appears inside the
 * sentence. Null when nothing fits, which the tool reports honestly.
 */
export function findNeed(query: string): NeedMatch | null {
  const q = (query || '').trim().toLowerCase();
  if (!q) return null;
  const slug = q.replace(/[\s_]+/g, '-').replace(/[^a-z-]/g, '');
  const direct = needBySlug(slug);
  if (direct) return { need: direct, matched: slug };
  for (const n of allNeeds()) {
    if (n.label.toLowerCase() === q) return { need: n, matched: n.label };
  }
  const ws = words(q);
  // multi word synonyms first ("end times")
  for (const [k, slugs] of Object.entries(SYNONYMS)) {
    if (k.includes(' ') && q.includes(k)) {
      for (const s of slugs) {
        const n = needBySlug(s);
        if (n) return { need: n, matched: k };
      }
    }
  }
  for (const w of ws) {
    const bare = w.replace(/'s$/, '');
    const n = needBySlug(bare);
    if (n) return { need: n, matched: bare };
    for (const s of SYNONYMS[bare] ?? []) {
      const hit = needBySlug(s);
      if (hit) return { need: hit, matched: bare };
    }
  }
  // a stemmed word: "grieving" -> "grief" is in SYNONYMS; "anxieties" -> anxiety
  for (const w of ws) {
    for (const n of allNeeds()) {
      const root = n.slug.replace(/-/g, ' ');
      if (w.length >= 5 && (root.startsWith(w.slice(0, 5)) || w.startsWith(root.slice(0, 5)))) {
        return { need: n, matched: w };
      }
    }
  }
  return null;
}
