/* ============================================================
   THE LIVING BREAD MCP, verses for a need.

   src/data/needs.json is generated by scripts/build-data.py from the same
   tables the web builder uses (verses_data NEEDS, build-landing
   VERSE_TOPICS, topics_data TOPICS, verse_topic_enrich), so the references
   here are the references on living-bread.org. It holds references and our
   own one-line reflections; the Scripture itself is read from the stored
   KJV at call time.

   Matching is deliberately forgiving: a person says "I'm scared" or "my
   mother died", not "fear" or "grief". Pure, so it can be tested anywhere.
   ============================================================ */
import NEEDS from './data/needs.json';

export interface NeedRef {
  ref: string;
  /** In our words, not His: a line on why this verse speaks here. */
  why?: string;
}

export interface Need {
  slug: string;
  label: string;
  lead: string;
  page: string;
  refs: NeedRef[];
}

const TABLE = NEEDS as Record<string, Omit<Need, 'slug'>>;

export function allNeeds(): Need[] {
  return Object.entries(TABLE).map(([slug, n]) => ({ slug, ...n }));
}

export function needBySlug(slug: string): Need | null {
  const n = TABLE[slug];
  return n ? { slug, ...n } : null;
}

